    fn section_stops_at_next_heading() {
        let text = "## 声明\n| a | b | c |\n## 范围\n- `x/`\n## 排除\n| y | z |\n";
        assert_eq!(section(text, "声明").len(), 1);
        assert_eq!(section(text, "范围").len(), 1);
        assert_eq!(section(text, "排除").len(), 1);
        assert!(section(text, "不存在").is_empty());
    }

