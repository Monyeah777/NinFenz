def load(root: str | Path = ".") -> dict[str, Any]:
    """Load and validate the canonical product metadata record."""
    path = Path(root) / REL
    doc = json_doc.load(path, dict, what=REL)
    if doc.get("schema") != SCHEMA:
        raise ValueError(f"{REL}: schema 必须是 {SCHEMA}")
    for key in _PRODUCT_SCALARS:
        if not isinstance(doc.get(key), str) or not doc[key].strip():
            raise ValueError(f"{REL}: {key} 必须是非空字符串")
    if not _VERSION.fullmatch(doc["version"]):
        raise ValueError(f"{REL}: version 必须形如 MAJOR.MINOR.PATCH")
    names = doc.get("distribution_names")
    if not isinstance(names, dict) or any(
            not isinstance(names.get(key), str) or not names[key]
            for key in _DISTRIBUTIONS):
        raise ValueError(f"{REL}: distribution_names 必须声明 python/npm/github_packages/mcp")
    bundle = doc.get("release_bundle")
    if not isinstance(bundle, dict):
        raise ValueError(f"{REL}: release_bundle 必须是对象")
    for key in _RELEASE_FILES:
        if not isinstance(bundle.get(key), str) or not bundle[key]:
            raise ValueError(f"{REL}: release_bundle.{key} 必须是非空路径")
    artifacts = bundle.get("required_artifacts")
    if not isinstance(artifacts, list) or not artifacts or not all(
            isinstance(item, str) and item for item in artifacts):
        raise ValueError(f"{REL}: release_bundle.required_artifacts 必须是非空字符串数组")
    if doc.get("release_bundle_required") is not True:
        raise ValueError(f"{REL}: release_bundle_required 必须为 true；发布束是产品面")
    if doc.get("paid_hosted_tier") is not False:
        raise ValueError(f"{REL}: paid_hosted_tier 必须为 false")
    if doc.get("commercial_license_available") is not True:
        raise ValueError(f"{REL}: commercial_license_available 必须为 true")
    return doc


def _json(path: Path) -> dict[str, Any]:
    return json_doc.load(path, dict, what=str(path))


def _json_projection(path: Path, updates: dict[str, Any]) -> str:
    doc = _json(path)
    for key, value in updates.items():
        doc[key] = copy.deepcopy(value)
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def _replace(text: str, pattern: str, replacement: str, label: str) -> str:
    updated, count = re.subn(pattern, replacement, text, count=1, flags=re.MULTILINE)
    if count != 1:
        raise ValueError(f"{label}: 找不到唯一投影位（修复指引：核对真源生成器与该文件）")
    return updated


def _project_distribution_files(r: Path, doc: dict[str, Any]) -> dict[str, str]:
    version = doc["version"]
    license_expression = doc["license_expression"]
    npm_license = doc["npm_license"]
    names = doc["distribution_names"]

    pyproject = (r / "pyproject.toml").read_text(encoding="utf-8")
    pyproject = _replace(pyproject, r'^version\s*=\s*"[^"]+"',
                         f'version = "{version}"', "pyproject.toml version")
    pyproject = _replace(
        pyproject,
        r'^description\s*=\s*"[^"]+"',
        'description = ' + json.dumps(doc["description"], ensure_ascii=False),
        "pyproject.toml description",
    )
    pyproject = _replace(
        pyproject,
        r'^license\s*=\s*\{[^\n]+\}',
        'license = { text = ' + json.dumps(license_expression) + ' }',
        "pyproject.toml license",
    )
    pyproject = re.sub(
        r'(?m)^\s*"License :: [^\n]+",?\n',
        '  "License :: OSI Approved :: GNU Affero General Public License v3",\n',
        pyproject,
        count=1,
    )
    if "sbom = [" not in pyproject:
        pyproject = _replace(
            pyproject,
            r'(?m)^sast\s*=\s*\[[^\n]+\]\n',
            lambda m: m.group(0) + (
                'sbom = ["cyclonedx-python-lib[json-validation]==11.12.0", '
                '"spdx-tools==0.8.3"]\n'
            ),
            "pyproject.toml sbom extra",
        )

    package = _json_projection(
        r / "packaging" / "npm" / "package.json",
        {
            "name": names["npm"],
            "version": version,
            "mcpName": names["mcp"],
            "description": doc["npm_description"],
            "license": npm_license,
        },
    )
    package_doc = json_doc.loads(package, dict, what="npm package projection")
    package_doc.setdefault("scripts", {})["release:build"] = (
        "python tools/build_release.py --out dist/release"
    )
    package = json.dumps(package_doc, ensure_ascii=False, indent=2) + "\n"
    mcp_package = _json_projection(
        r / "protocol" / "mcp_package.json", {"version": version})
    server = _json_projection(
        r / "packaging" / "mcp" / "server.json",
        {"name": names["mcp"], "version": version},
    )
    server_doc = json_doc.loads(server, dict, what="MCP server projection")
    entries = server_doc.get("packages")
    if not isinstance(entries, list) or not entries:
        raise ValueError(
            "packaging/mcp/server.json: packages 不能为空"
            "（修复指引：恢复至少一个 MCP 分发包声明）")
    for entry in entries:
        entry["version"] = version
        if "identifier" in entry:
            entry["identifier"] = names["npm"]
    server = json.dumps(server_doc, ensure_ascii=False, indent=2) + "\n"
    codemeta = _json_projection(
        r / "codemeta.json",
        {
            "name": doc["name"],
            "version": version,
            "license": license_expression,
            "codeRepository": doc["repository"],
            "url": doc["homepage"],
        },
    )
    citation = (r / "CITATION.cff").read_text(encoding="utf-8")
    citation = _replace(citation, r"^license:\s*.*$",
                        f"license: {license_expression}", "CITATION.cff license")
    if not re.search(r"(?m)^license-url:", citation):
        citation = citation.replace(
            "license: " + license_expression + "\n",
            "license: " + license_expression
            + f'\nlicense-url: "{doc["license_url"]}"\n', 1)
    citation = _replace(citation, r"^license-url:\s*.*$",
                        f'license-url: "{doc["license_url"]}"',
                        "CITATION.cff license-url")
    hf = (r / "packaging" / "hf-space" / "Dockerfile").read_text(encoding="utf-8")
    hf = _replace(hf, r"^ARG NF_VERSION=\d+\.\d+\.\d+$",
                  f"ARG NF_VERSION={version}", "HF Space Dockerfile version")
    dotnet_path = r / "engine" / "dotnet" / "tools" / "nf-dotnet" / "Program.cs"
    dotnet = _replace(
        dotnet_path.read_text(encoding="utf-8"),
        r'const string NfCliVersion = "[^"]+";',
        f'const string NfCliVersion = "{version}";',
        ".NET CLI version",
    )
    return {
        "pyproject.toml": pyproject,
        "packaging/npm/package.json": package,
        "protocol/mcp_package.json": mcp_package,
        "packaging/mcp/server.json": server,
        "codemeta.json": codemeta,
        "CITATION.cff": citation,
        "packaging/hf-space/Dockerfile": hf,
        "engine/dotnet/tools/nf-dotnet/Program.cs": dotnet,
    }


def _project_facts(r: Path, doc: dict[str, Any]) -> str:
    version = doc["version"]
    license_expression = doc["license_expression"]
    names = doc["distribution_names"]
    facts_doc = _json(r / "site" / "facts.json")
    official = facts_doc.setdefault("official", {})
    official["statement_zh"] = (
        "官方唯一指定入口是 https://ninfenz.dev。NinFenz 不提供付费托管版或客户端下载，"
        "也不会通过非官方渠道索取账号、手机号或支付信息；闭源商业使用另需商业许可，"
        "条款见 COMMERCIAL.md。"
    )
    official["statement_en"] = (
        "The only official entry point is https://ninfenz.dev. NinFenz has no paid "
        "hosted edition or client download and never requests account, phone, or payment "
        "details through unofficial channels; closed-source commercial use requires a "
        "separate commercial licence under COMMERCIAL.md."
    )
    official["license_allows"] = (
        f"{license_expression}: AGPL source rights plus a commercial option")
    official["license_requires"] = (
        "preserve notices; network users of modified AGPL code must receive its source")
    subject = facts_doc.setdefault("subject", {})
    subject["license"] = license_expression
    citations = facts_doc.setdefault("citation", {})
    if "plain" in citations:
        citations["plain"] = (
            f'NinFenz（NF）— 内容契约层，{doc["author"]}，'
            f'{license_expression}，{doc["repository"]}'
        )
    if "apa" in citations:
        citations["apa"] = (
            f'{doc["author"]}. (2026). NinFenz (宁封子): a content contract layer '
            f'[Computer software]. {license_expression}. {doc["homepage"]}'
        )
    if "bibtex" in citations:
        citations["bibtex"] = citations["bibtex"].replace(
            "license = {MIT}", f"license = {{{license_expression}}}")
    for fact in facts_doc.get("facts") or []:
        if fact.get("id") == "npm":
            fact["claim_zh"] = re.sub(r"v\d+\.\d+\.\d+", f"v{version}",
                                      str(fact.get("claim_zh") or ""))
            fact["claim_en"] = re.sub(r"v\d+\.\d+\.\d+", f"v{version}",
                                      str(fact.get("claim_en") or ""))
    facts_doc.setdefault("machine_endpoints", {})["npm_provenance"] = (
        f"https://registry.npmjs.org/-/npm/v1/attestations/"
        f"{names['npm']}@{version}"
    )
    limits = facts_doc.setdefault("limits", {})
    limits["paid_tier"] = False
    limits["commercial_license_available"] = True
    return json.dumps(facts_doc, ensure_ascii=False, indent=2) + "\n"


def _public_claims(text: str, doc: dict[str, Any]) -> str:
    short_license = "AGPL-3.0-only / Commercial"
    version = doc["version"]
    text = text.replace("https://opensource.org/license/mit", doc["license_url"])
    text = re.sub(r'(?m)^(\s*"softwareVersion"\s*:\s*)"[^"]+"',
                  rf'\1"{version}"', text)
    text = re.sub(r"(?<![0-9A-Za-z.])1\.\d+\.\d+(?![0-9A-Za-z.])", version, text)
    text = text.replace("license = {MIT}",
                        f"license = {{{doc['license_expression']}}}")
    text = text.replace(">MIT<", f">{short_license}<")
    text = re.sub(r"\bMIT\b", short_license, text)
    text = text.replace("没有付费版", "没有付费托管版（闭源商业使用另需商业许可）")
    text = text.replace("无付费版", "无付费托管版")
    text = text.replace("no paid version", "no paid hosted version")
    text = text.replace("No paid version", "No paid hosted version")
    text = text.replace("no paid tier", "no paid hosted tier")
    text = text.replace("No paid tier", "No paid hosted tier")
    return text.replace(
        "NF never charges and has no support desk",
        "NF takes no payment through unofficial channels; commercial terms "
        "are documented in COMMERCIAL.md",
    )


